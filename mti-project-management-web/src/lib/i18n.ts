export type TranslationKey = keyof typeof translations.en;

export function getTranslation(key: TranslationKey, lang: Language): string {
  const dict = translations[lang] || translations.ar;
  return (dict as any)[key] || (translations.ar as any)[key] || (translations.en as any)[key] || key;
}

export function formatDateCairo(isoString?: string | null, lang: Language = 'ar'): string {
  if (!isoString) return '—';
  try {
    const d = new Date(isoString);
    const locale = lang === 'ar' ? 'ar-EG' : 'en-US';
    return new Intl.DateTimeFormat(locale, {
      timeZone: 'Africa/Cairo',
      year: 'numeric',
      month: 'short',
      day: 'numeric',
      hour: '2-digit',
      minute: '2-digit'
    }).format(d);
  } catch {
    return isoString;
  }
}
